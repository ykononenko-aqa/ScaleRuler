package com.ykononenko.state

/**
 * Состояния экранного сценария работы приложения.
 *
 * Переходы выполняются кнопками из пакета [com.ykononenko.controls]: каждая
 * кнопка хранит допустимые состояния и целевое состояние.
 */
enum class AppState {

    /** Начальное состояние: фото ещё не загружено. */
    IDLE,

    /** Фото загружено, линейка ещё не построена. */
    PHOTO_LOADED,

    /** Ожидается постановка первой калибровочной точки. */
    AWAITING_POINT_1,

    /** Ожидается постановка второй калибровочной точки. */
    AWAITING_POINT_2,

    /** Обе точки поставлены, ожидается ввод реального размера в миллиметрах. */
    POINTS_SET,

    /** Линейка построена и размещена; доступны перетаскивание и сохранение. */
    RULER_PLACED,

    /**
     * Работа только с указателем на север (линейки может не быть) либо
     * указатель добавлен поверх уже размещённой линейки.
     *
     * Доступны перемещение и поворот указателя, смена его цвета и размера,
     * сохранение изображения, а также пакетная обработка, если линейка есть.
     * Линейка из этого состояния больше не изменяется.
     */
    NORTH_PLACED
}
